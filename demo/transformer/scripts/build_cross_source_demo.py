#!/usr/bin/env python3
"""Package verified aggregate facts as static browser data, never source logs."""
import argparse
import hashlib
import json
from pathlib import Path


def fail_constant(value):
    raise ValueError(f"Non-JSON numeric constant: {value}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("aggregate_json", type=Path)
    args = parser.parse_args()
    raw = args.aggregate_json.read_bytes()
    data = json.loads(raw, parse_constant=fail_constant)
    if data.get("schema_version") != "1.0.0" or data.get("metric", {}).get("id") != "recorded_help_request_observations":
        raise ValueError("Unsupported aggregate schema/metric")
    if data.get("distribution_scope") != "research_aggregate_facts_only_no_raw_redistribution":
        raise ValueError("Only aggregate-facts artifacts may enter this static demo")
    verification = data["pipeline_verification"]
    for key in ["direct_native_baseline_matches", "carrier_aggregates_identical", "order_and_batch_invariant", "replay_idempotent", "conflicting_duplicate_rejected", "unknown_coverage_preserved"]:
        if verification.get(key) is not True:
            raise ValueError(f"Required pipeline check did not pass: {key}")
    if verification.get("private_row_artifacts_in_public_output") is not False:
        raise ValueError("Public aggregate must explicitly exclude private row artifacts")
    sources = data["sources"]
    if not sources or len({source["source_id"] for source in sources}) != len(sources):
        raise ValueError("Source strata must be present and distinct")
    counts = [source["assistance_request_observations"] for source in sources]
    if any(type(value) is not int or value < 0 for value in counts):
        raise ValueError("Counts must be non-negative integers")
    aggregate = data["aggregate"]
    if aggregate["source_count"] != len(sources) or aggregate["assistance_request_observations"] != sum(counts):
        raise ValueError("Aggregate arithmetic does not reconcile")
    for key in ["actual_request_total", "unique_cross_source_learners", "request_rate", "learning_effect"]:
        if aggregate.get(key, "missing") is not None:
            raise ValueError(f"Unsupported inferred quantity: {key}")
    for key in ["capture_profile_records", "contract_validations", "xapi_roundtrips", "caliper_roundtrips"]:
        if verification.get(key) != sum(counts):
            raise ValueError(f"Capture/binding count does not reconcile: {key}")
    root = Path(__file__).resolve().parents[1]
    target = root / "dist/examples/cross-source-analysis.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(raw)
    (root / "dist/cross-source-analysis-data.mjs").write_text(
        "// Generated by scripts/build_cross_source_demo.py; aggregate facts only.\n"
        "export default " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    print(json.dumps({"input_sha256":hashlib.sha256(raw).hexdigest(), "source_count":len(sources), "recorded_request_observations":sum(counts), "raw_payloads_packaged":False}))


if __name__ == "__main__":
    main()
