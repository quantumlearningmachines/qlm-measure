"""Package verified Python binding fixtures as inert static website data.

No binding logic is implemented here. The JSON bytes are copied unchanged;
the module serializes the exact parsed JSON for use with connect-src 'none'.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


def build(source: Path, destination: Path) -> dict:
    raw = source.read_bytes()
    data = json.loads(raw)
    if not isinstance(data.get("provenance"), dict):
        raise ValueError("Binding fixture provenance is required.")
    if set(data.get("examples", {})) != {"requested", "generated", "displayed"}:
        raise ValueError("Expected the three documented synthetic fixtures.")
    required = {"assistance_capture", "xapi_statement", "caliper_event", "caliper_envelope"}
    for lifecycle, record in data["examples"].items():
        if not required.issubset(record) or not all(isinstance(record[key], dict) for key in required):
            raise ValueError(f"Incomplete carrier representations: {lifecycle}")
    destination.mkdir(parents=True, exist_ok=True)
    examples = destination / "examples"
    examples.mkdir(exist_ok=True)
    (examples / "assistance-profile-bindings.json").write_bytes(raw)
    module = ("// Generated by scripts/build_profile_examples.py from verified Python output.\n"
              "// Inert synthetic fixture data; no browser-side carrier reconstruction.\n"
              "export default " + json.dumps(data, ensure_ascii=True, indent=2, allow_nan=False) + ";\n")
    module_path = destination / "assistance-profile-examples.mjs"
    module_path.write_text(module, encoding="utf-8")
    return {"source_sha256": hashlib.sha256(raw).hexdigest(), "examples": len(data["examples"]),
            "module_sha256": hashlib.sha256(module.encode()).hexdigest(),
            "scope": "Exact source bytes copied; parsed JSON serialized as an inert module. No interoperability validation performed by this packaging step."}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--dist", type=Path, default=Path(__file__).resolve().parents[1] / "dist")
    arguments = parser.parse_args()
    print(json.dumps(build(arguments.source, arguments.dist), indent=2))
